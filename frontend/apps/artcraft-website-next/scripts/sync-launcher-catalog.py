#!/usr/bin/env python3
"""Export committed launcher data without building its UI or fetching dependencies."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tarfile
import tempfile
import tomllib

APP = Path(__file__).resolve().parents[1]


def git(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("launcher", type=Path)
    parser.add_argument("--revision", default="HEAD")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    revision = git(args.launcher, "rev-parse", f"{args.revision}^{{commit}}").decode().strip()
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        archive = git(args.launcher, "archive", revision)
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            tar.extractall(root, filter="data")
        # Compile the real source modules, including desktop metadata, rather than parse Rust.
        modules = {
            "catalog": root / "crates/core/src/catalog.rs",
            "details": root / "crates/core/src/details.rs",
            "desktop_entry": root / "crates/native/src/desktop_entry.rs",
        }
        wrapper = root / "export.rs"
        wrapper.write_text(
            '#![allow(dead_code)]\nextern crate self as artcraft_launcher_core;\n'
            '#[derive(PartialEq)] pub enum PackageKind { Dmg }\n'
            'pub enum Os { FreeBsd, Linux, MacOs, Windows }\n'
            + "".join(f'#[path = {json.dumps(str(path))}] pub mod {name};\n' for name, path in modules.items())
            + 'pub use catalog::CraftApp;\n'
            + (APP / "scripts/export-launcher-catalog.rs").read_text().replace(
                'use artcraft_launcher_core::{catalog, details, desktop_entry};', '')
        )
        executable = root / "export"
        subprocess.run(["rustc", "--edition=2021", str(wrapper), "-o", str(executable)], check=True)
        catalog = subprocess.check_output([str(executable)]).decode()
        parsed = tomllib.loads(catalog)
        ids = [app["id"] for app in parsed["apps"]]
        if len(ids) != len(set(ids)):
            raise ValueError("Duplicate app IDs")
        outputs = {}
        attribution = (root / "ATTRIBUTION.md").read_text().splitlines()
        rows = []
        for app in parsed["apps"]:
            app_id = app["id"]
            icon = (root / f"assets/app-icons/{app_id}.png").read_bytes()
            digest = hashlib.sha256(icon).hexdigest()
            filename = f"{app_id}-{digest}.png"
            outputs[f"launcher-app-icons/{filename}"] = icon
            catalog = catalog.replace(
                f'startup_wm_class = {json.dumps(app["startup_wm_class"])}\n',
                f'startup_wm_class = {json.dumps(app["startup_wm_class"])}\nicon_url = "https://getartcraft.com/launcher-app-icons/{filename}"\nicon_sha256 = "{digest}"\n',
            )
            row = next(line for line in attribution if line.startswith(f'| `assets/app-icons/{app_id}.png` |'))
            row = row.replace(f"assets/app-icons/{app_id}.png", f"public/launcher-app-icons/{filename}")
            row = row.replace("assets/app-icons/LICENSE-", "LICENSE-")
            row = row.replace(
                "(docs/brand/LICENSE-brand.txt)",
                f"(https://github.com/storytold/craft-launcher/blob/{revision}/docs/brand/LICENSE-brand.txt)",
            )
            rows.append([cell.strip() for cell in row.strip('|').split('|')])
        # Keep Markdown tables readable in source as well as rendered.
        table = [["Path", "Title", "Author", "Source", "License"]] + rows
        widths = [max(len(row[i]) for row in table) for i in range(5)]
        table.insert(1, ["-" * width for width in widths])
        text = "# ArtCraft Launcher app icons\n\nUnmodified launcher icons; filenames contain the app ID and SHA-256 hash.\n\n"
        text += "\n".join("| " + " | ".join(cell.ljust(width) for cell, width in zip(row, widths)) + " |" for row in table) + "\n"
        outputs["launcher-app-icons/ATTRIBUTION.md"] = text.encode()
        for license_file in (root / "assets/app-icons").glob("LICENSE-*.txt"):
            outputs[f"launcher-app-icons/{license_file.name}"] = license_file.read_bytes()
        header = (
            "# ArtCraft Launcher catalog, served at https://getartcraft.com/launcher-catalog.toml.\n"
            f"# Source: storytold/craft-launcher at {revision}\n"
            "# Generated by scripts/sync-launcher-catalog.py; preserve the existing TOML schema.\n"
            "# Verify launcher-catalog.toml.sig with the launcher's pinned Ed25519 key before use.\n"
            "# Install sources must still follow the launcher's approved-source policy.\n"
        )
        outputs["launcher-catalog.toml"] = (header + catalog).encode()
        # Parsing the final file also catches strings Rust Debug cannot represent as TOML.
        final = tomllib.loads(outputs["launcher-catalog.toml"].decode())
        assert len(final["apps"]) == len(ids)
        mismatches = []
        for name, data in outputs.items():
            path = APP / "public" / name
            if args.check:
                if not path.exists() or path.read_bytes() != data:
                    mismatches.append(name)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
        if mismatches:
            raise SystemExit("Catalog differs from launcher: " + ", ".join(mismatches))
        print(f'{"Verified" if args.check else "Exported"} {len(ids)} apps from {revision}')


if __name__ == "__main__":
    main()
